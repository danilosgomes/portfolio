function setupReveals() {
  if (observer) observer.disconnect();
  observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.08, rootMargin: "0px 0px -4%" });
  document.querySelectorAll(".reveal").forEach(el => observer.observe(el));
}

function updateLightboxImage(index) {
  if (!lightboxImages.length) return;
  lightboxIndex = (index + lightboxImages.length) % lightboxImages.length;
  const source = lightboxImages[lightboxIndex];
  lightboxImage.src = source.currentSrc || source.src;
  lightboxImage.alt = source.alt;
  lightboxCaption.textContent = source.alt;
  lightbox.classList.toggle("is-single", lightboxImages.length < 2);
}

function openLightbox(source) {
  clearTimeout(lightboxCloseTimer);
  lightboxImages = Array.from(main.querySelectorAll(".black-media.has-image img"));
  updateLightboxImage(lightboxImages.indexOf(source));
  if (!lightbox.open) lightbox.showModal();
  body.classList.add("lightbox-open");
  requestAnimationFrame(() => {
    lightbox.classList.add("is-visible");
    lightboxClose.focus();
  });
}

function closeLightbox() {
  if (!lightbox.open) return;
  lightbox.classList.remove("is-visible");
  body.classList.remove("lightbox-open");
  lightboxCloseTimer = setTimeout(() => {
    lightbox.close();
    lightboxImage.removeAttribute("src");
  }, 350);
}

function moveLightbox(step) {
  updateLightboxImage(lightboxIndex + step);
}

