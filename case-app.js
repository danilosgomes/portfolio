function setupCursorTargets() {
  document.querySelectorAll(".cursor-target").forEach(target => {
    target.addEventListener("mouseenter", () => cursor.classList.add("is-active"));
    target.addEventListener("mouseleave", () => cursor.classList.remove("is-active"));
  });
}

function render() {
  cursor.classList.remove("is-active");
  if (location.hash && !location.hash.startsWith("#/")) return;
  const route = location.hash.replace(/^#\//, "");
  const [page, slug] = route.split("/");
  const project = page === "case" ? portfolio.projects.find(item => item.slug === slug) : null;

  if (project) {
    main.innerHTML = caseTemplate(project);
    document.title = `${project.title} — ${portfolio.name}`;
  } else if (page === "about") {
    main.innerHTML = aboutTemplate();
    document.title = `${portfolio.aboutTitle || "Sobre mim"} — ${portfolio.name}`;
  } else {
    main.innerHTML = homeTemplate();
    document.title = `${portfolio.name} — ${portfolio.role}`;
  }

  // Highlight active link in navigation
  document.querySelectorAll(".site-nav a").forEach(link => {
    const href = link.getAttribute("href");
    const isActive = 
      (page === "about" && href === "#/about") ||
      (page === "work" && href === "#/work") ||
      ((!page || page === "") && href === "#/");
    link.classList.toggle("is-active", Boolean(isActive));
  });

  syncGlobalContent();
  setupReveals();
  setupCursorTargets();
  closeMenu();

  requestAnimationFrame(() => {
    if (!project && page === "work") {
      const section = document.getElementById("work");
      if (section) section.scrollIntoView({ behavior: "smooth" });
    } else {
      window.scrollTo(0, 0);
    }
  });
}

function closeMenu() {
  body.classList.remove("is-menu-open");
  menuButton.setAttribute("aria-expanded", "false");
}

menuButton.addEventListener("click", () => {
  const open = body.classList.toggle("is-menu-open");
  menuButton.setAttribute("aria-expanded", String(open));
});

nav.addEventListener("click", closeMenu);
lightboxClose.addEventListener("click", closeLightbox);
lightboxPrevious.addEventListener("click", () => moveLightbox(-1));
lightboxNext.addEventListener("click", () => moveLightbox(1));
